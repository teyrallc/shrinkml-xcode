import Foundation

/// The text of every file the importer writes that is not copied out of an archive: `Package.swift`,
/// the umbrella `Exports.swift`, `.gitignore`, and per model a `<Name>Files.swift` (and, for an
/// invoice reader, a `<Name>Runtime.swift`). Everything here is a plain function of the lock (and, for
/// an invoice reader, of what its bundle says about itself): the same input is the same bytes, which is
/// what lets an import be repeated with no diff.
enum Generators {
  /// The line in `Package.swift` that remembers where the import package lives.
  static let importPackageMarker = "// shrinkml-import-package: "

  static let topLevelPaths = ["Package.swift", ".gitignore", "Sources/ShrinkMLModels/Exports.swift"]

  /// A Swift string literal for text that is plain; anything outside printable ASCII is escaped.
  static func literal(_ text: String) -> String {
    var out = "\""
    for scalar in text.unicodeScalars {
      switch scalar {
      case "\"": out += "\\\""
      case "\\": out += "\\\\"
      case "\n": out += "\\n"
      case "\t": out += "\\t"
      default:
        if scalar.value >= 0x20 && scalar.value <= 0x7E {
          out.unicodeScalars.append(scalar)
        } else {
          out += "\\u{\(String(scalar.value, radix: 16))}"
        }
      }
    }
    return out + "\""
  }

  /// A path to the import package that is safe to put in a manifest: relative or absolute, only
  /// characters a path normally has, never a quote or a backslash.
  static func isSafeImportPackagePath(_ path: String) -> Bool {
    !path.isEmpty && path.utf8.count <= 512
      && path.unicodeScalars.allSatisfy {
        ($0.value >= 0x30 && $0.value <= 0x39) || ($0.value >= 0x41 && $0.value <= 0x5A)
          || ($0.value >= 0x61 && $0.value <= 0x7A) || "._-/+".unicodeScalars.contains($0)
      }
  }

  /// The import-package path a `Package.swift` remembers, or nil.
  static func importPackagePath(inManifest text: String) -> String? {
    for line in text.split(separator: "\n", omittingEmptySubsequences: true).prefix(12) where line.hasPrefix(importPackageMarker) {
      let path = String(line.dropFirst(importPackageMarker.count)).trimmingCharacters(in: .whitespaces)
      return isSafeImportPackagePath(path) ? path : nil
    }
    return nil
  }

  // MARK: Top level

  static func gitignore() -> String {
    """
    # Generated by ShrinkML Import (shrinkml.lock.v1). You may edit it: an edited copy is never
    # overwritten, a .gitignore.new is written beside it instead.
    # 這個檔案由 ShrinkML 匯入產生。你可以改；改過的版本不會被覆蓋，新的內容會寫成 .gitignore.new。

    # Staging, orphans and (for an invoice reader) the Swift runtime. The runtime's licence does not
    # allow passing its source on to anyone, so it stays out of git: re-import the kit to restore it.
    .shrinkml/

    # The archives you drop in. Their contents are already in Sources/ and Records/.
    Inbox/

    .build/
    .swiftpm/

    """
  }

  static func exportsSwift(models: [LockedModel]) -> String {
    var out = """
      // Generated by ShrinkML Import (shrinkml.lock.v1). Do not edit: the next import replaces this file
      // only while it still matches shrinkml.lock.json, otherwise it writes Exports.swift.new beside it.
      // 這個檔案由 ShrinkML 匯入產生，請不要改；改過的話，下次匯入會寫成 Exports.swift.new，不會蓋掉你的。
      //
      // `import ShrinkMLModels` brings in every model below.

      """
    if models.isEmpty { out += "// (no model has been imported yet)\n" }
    for model in models.sorted(by: { $0.name < $1.name }) {
      if model.kind == .pipelineKit {
        out += "#if canImport(\(model.name))\n@_exported import \(model.name)\n#endif\n"
      } else {
        out += "@_exported import \(model.name)\n"
      }
    }
    return out
  }

  /// `importPackage` is a path to a local checkout of the import package (development): it wins. Without it the
  /// manifest depends on the public repository (`PublicRepository`, `.package(url:from:)`).
  static func packageSwift(
    models: [LockedModel], importPackage: String?, repository: PublicRepository = .current
  ) -> String {
    let sorted = models.sorted { $0.name < $1.name }
    let hasKit = sorted.contains { $0.kind == .pipelineKit }
    var out = "// swift-tools-version:6.0\n"
    out += """
      // Generated by ShrinkML Import (shrinkml.lock.v1). Do not edit: the next import replaces this file
      // only while it still matches shrinkml.lock.json, otherwise it writes Package.swift.new beside it
      // and tells you what differs. Your own code goes in Sources/<Name>/Overrides/.
      // 這個檔案由 ShrinkML 匯入產生，請不要改；改過的話，下次匯入會寫成 Package.swift.new 並告訴你差在哪。
      // 你自己的程式放在 Sources/<模型名>/Overrides/。

      """
    if let importPackage { out += importPackageMarker + importPackage + "\n" }
    out += """
      //
      // Every model folder is declared with .copy, never .process. SwiftPM's .process of an .mlpackage runs
      // Xcode's coremlc: `swift build` under the Command Line Tools fails on it, and Xcode makes a Swift class
      // named after the file, which clashes between hand-overs (every file is called model_fp32 or model_fp16).
      // A copied .mlpackage builds everywhere. The model's Swift file loads the compiled copy (.mlmodelc) the
      // hand-over holds, and compiles the .mlpackage (MLModel.compileModel(at:)) only when that copy is missing
      // or cannot be loaded. `.process` also works under xcodebuild; it is not used for those two reasons.
      // 每個模型資料夾都用 .copy 宣告，不用 .process：.process 會呼叫 Xcode 的 coremlc，
      // 在只裝 Command Line Tools 時 swift build 會失敗，而且 Xcode 會用檔名產生一個 Swift 類別，
      // 不同交付的檔名都是 model_fp32／model_fp16，類別會撞名。.copy 的 .mlpackage 到處都能建置，
      // 模型的 Swift 檔先載入交付附的已編譯副本（.mlmodelc）；副本不存在或載入不了時，才編譯 .mlpackage
      // （MLModel.compileModel(at:)）。


      """
    out += hasKit ? "import Foundation\n" : ""
    out += "import PackageDescription\n\n"

    func resourceLines(_ model: LockedModel) -> String {
      var parts: [String] = []
      let older = model.previousRevisions.map { "\"Resources/r\($0.revision)\"" }
      if !older.isEmpty { parts.append("exclude: [\(older.joined(separator: ", "))]") }
      // .copy, never .process: a Core ML model is `.copy`ed as a folder (see the note at the top). A
      // Core ML target copies the model's own folder `Models`, the invoice target its revision folder.
      let folder = model.kind == .coremlBundle ? "Resources/r\(model.revision)/Models" : "Resources/r\(model.revision)"
      parts.append("resources: [.copy(\"\(folder)\")]")
      return parts.joined(separator: ",\n      ")
    }
    let dependencyLines =
      importPackage.map { "    .package(path: \(literal($0)))," } ?? repository.dependencyLine ?? ""

    if !hasKit {
      out += "let package = Package(\n"
      out += "  name: \"ShrinkMLModels\",\n  platforms: [.macOS(.v14), .iOS(.v17)],\n"
      out += "  products: [.library(name: \"ShrinkMLModels\", targets: [\"ShrinkMLModels\"])],\n"
      out += "  dependencies: [\(dependencyLines.isEmpty ? "" : "\n" + dependencyLines + "\n  ")],\n"
      out += "  targets: [\n"
      let names = sorted.map { "\"\($0.name)\"" }.joined(separator: ", ")
      out += "    .target(name: \"ShrinkMLModels\", dependencies: [\(names)]),\n"
      for model in sorted {
        out += "    .target(\n      name: \"\(model.name)\",\n      \(resourceLines(model))\n    ),\n"
      }
      out += "  ],\n  swiftLanguageModes: [.v5]\n)\n"
      return out
    }

    out += """
      // The Pipeline Bundle runtime is kept in .shrinkml/runtime, which is not in git: its licence does not
      // allow passing the source on to anyone. On a fresh clone it is absent; the invoice reader is then left
      // out of this package (so everything else still builds) until you import its kit again.
      // 發票讀取用的 runtime 放在 .shrinkml/runtime（不進 git，因為授權不許轉交原始碼）。剛 clone 下來時它不在，
      // 這時發票讀取模組會先被排除，其他模型照常建置；再匯入一次發票交付就會回來。
      let runtimeFolder = URL(fileURLWithPath: #filePath)
        .deletingLastPathComponent().appendingPathComponent(".shrinkml/runtime")
      let runtimeIsHere = FileManager.default.fileExists(
        atPath: runtimeFolder.appendingPathComponent("Package.swift").path)

      var dependencies: [Package.Dependency] = [\(dependencyLines.isEmpty ? "" : "\n" + dependencyLines + "\n")]
      var umbrella: [Target.Dependency] = [
      """
    out += "\n"
    for model in sorted where model.kind != .pipelineKit { out += "  \"\(model.name)\",\n" }
    out += "]\nvar targets: [Target] = [\n"
    for model in sorted where model.kind != .pipelineKit {
      out += "  .target(\n    name: \"\(model.name)\",\n    \(resourceLines(model).replacingOccurrences(of: "\n      ", with: "\n    "))\n  ),\n"
    }
    out += "]\n\nif runtimeIsHere {\n  dependencies.append(.package(path: \".shrinkml/runtime\"))\n"
    for model in sorted where model.kind == .pipelineKit {
      out += "  umbrella.append(\"\(model.name)\")\n  targets.append(\n    .target(\n      name: \"\(model.name)\",\n"
      out += "      dependencies: [.product(name: \"ShrinkMLPipelineRuntime\", package: \"runtime\")],\n"
      out += "      \(resourceLines(model))\n    ))\n"
    }
    out += "}\n\ntargets.append(.target(name: \"ShrinkMLModels\", dependencies: umbrella))\n\n"
    out += """
      let package = Package(
        name: "ShrinkMLModels",
        platforms: [.macOS(.v14), .iOS(.v17)],
        products: [.library(name: "ShrinkMLModels", targets: ["ShrinkMLModels"])],
        dependencies: dependencies,
        targets: targets,
        swiftLanguageModes: [.v5]
      )

      """
    return out
  }

  // MARK: Per model

  static func overridesPlaceholder(name: String) -> String {
    """
    // This folder is yours. ShrinkML Import never reads, rewrites or deletes anything in it, and
    // no lock entry tracks it. Put the code that goes with \(name) here.
    // 這個資料夾是你的。ShrinkML 匯入從不讀、不改、不刪這裡的任何東西，lock 也不記它。把配合 \(name) 的程式放在這裡。

    """
  }

  private static func header(_ model: LockedModel, file: String) -> String {
    """
    // Generated by ShrinkML Import (shrinkml.lock.v1): revision \(model.revision) of "\(model.name)".
    // Do not edit. The next import replaces this file only while it still matches shrinkml.lock.json;
    // otherwise it writes \(file).new beside it. Your own code goes in ../Overrides/.
    // 這個檔案由 ShrinkML 匯入產生，請不要改；改過的話，下次匯入會寫成 \(file).new，不會蓋掉你的。你的程式放在 ../Overrides/。

    """
  }

  /// The addresses of this model's files inside the module's resource bundle, and what the hand-over
  /// said about itself. It does not run anything.
  static func filesSwift(model: LockedModel, kit: KitFacts?) -> String {
    let file = "\(model.name)Files.swift"
    var out = header(model, file: file)
    out += """
      //
      // What this file is: the addresses of the files of this model in the module's resource bundle, and
      // what the hand-over said about itself. What it is NOT: it does not run the model, and it has no
      // pre-processing, decoding or labels logic. The archive itself carries no Swift file; when the answer
      // of the swift-package route was imported with it, that Swift file sits beside this one.
      // 這個檔案只是這個模型的檔案在資源包裡的位置，加上交付自己說的話。它不執行模型，沒有前處理、解碼或標籤的邏輯：
      // 交付的壓縮檔本身沒有 Swift 檔；如果同時匯入了 swift-package 路徑的回應，那個 Swift 檔會放在這個檔案旁邊。
      import Foundation

      public enum \(model.name)Files {
        public static let revision = \(model.revision)
        public static let archiveSHA256 = \(literal(model.archive.sha256))
        public static let road = \(literal(model.road))
        public static let format = \(literal(model.format))
        /// \(model.whatShipped.rawValue): as the archive's own roles say; "not_stated" when it said nothing.
        public static let whatShipped = \(literal(model.whatShipped.rawValue))
        /// "\(model.scorecard.status.rawValue)": "not_recorded" means the archive carried no scorecard (not that nothing was measured).
        public static let scorecard = \(literal(model.scorecard.status.rawValue))
        /// nil: neither the archive nor a record says whether a Swift file for it runs from start to end.
        /// true or false: what the record of the swift-package route says (ShrinkML's claim; this import ran nothing).
        public static let swiftRunsEndToEnd: Bool? = \(model.swiftRunsEndToEnd.map { $0 ? "true" : "false" } ?? "nil")

      """
    if model.kind == .coremlBundle {
      let typeName = TypeName.derive(from: model.name)
      let folder = TypeName.resourceDirectory(for: typeName)
      let prefix = "\(model.resourceDirectory)/\(folder)/"
      let packages = Set(
        model.files.compactMap { file -> String? in
          guard file.role == .model, file.path.hasPrefix(prefix) else { return nil }
          return file.path.dropFirst(prefix.count).split(separator: "/").first.map(String.init)
        }
      ).map { ($0 as NSString).deletingPathExtension }.sorted()
      let flat = model.files.filter { ($0.role == .sidecar || $0.role == .manifest) && $0.path.hasPrefix(prefix) }
        .map { String($0.path.dropFirst(prefix.count)) }.sorted()
      // The record is what brings the Swift file, so the record is what this file tells them apart by.
      let hasSwiftFile = model.files.contains { $0.role == .record && $0.path == "\(model.recordDirectory)/\(PackageFlavourFile.memberName)" }
      let swiftNote =
        hasSwiftFile
        ? "/// \(TypeName.swiftFile(for: typeName)) in this folder is the Swift file ShrinkML wrote for this model (the package flavour); it declares `\(typeName)`."
        : "/// There is no Swift file for this model here: the hand-over carried none. Ask the swift-package route for `type_name=\(typeName)` and import again."
      out += """
          /// The folder of this hand-over inside the module's resource bundle, as it was copied (`.copy`), nothing compiled.
          public static let resourceDirectory = \(literal(folder))
          /// The Swift type the package flavour of the Swift file declares for this model.
          public static let typeName = \(literal(typeName))
          \(swiftNote)
          /// The .mlpackage folders of the hand-over (without the extension): one, or two for a model in two parts.
          public static let modelPackages: [String] = [\(packages.map(literal).joined(separator: ", "))]
          /// A model package inside the copied folder. The model's Swift file loads the compiled copy the hand-over holds and compiles this package (`MLModel.compileModel(at:)`) only when that copy is missing or cannot be loaded.
          public static func modelPackageURL(named name: String) -> URL? {
            Bundle.module.url(forResource: name, withExtension: "mlpackage", subdirectory: resourceDirectory)
          }
          /// The other files of the hand-over, in the same folder.
          public static let resourceFiles: [String] = [\(flat.map(literal).joined(separator: ", "))]
          public static func url(forResourceFile fileName: String) -> URL? {
            let file = fileName as NSString
            return Bundle.module.url(
              forResource: file.deletingPathExtension, withExtension: file.pathExtension.isEmpty ? nil : file.pathExtension,
              subdirectory: resourceDirectory)
          }
        }

        """
    } else {
      out += """
          public static let runtimeVersion = \(literal(kit?.runtimeVersion ?? ""))
          /// The bundle (a zip) the Swift runtime reads. See \(model.name)Runtime.swift to open it.
          public static var pipelineBundleURL: URL? {
            Bundle.module.url(forResource: "pipeline-bundle", withExtension: "zip", subdirectory: "r\(model.revision)")
          }
        }

        """
    }
    return out
  }

  static func runtimeSwift(model: LockedModel, kit: KitFacts) -> String {
    let file = "\(model.name)Runtime.swift"
    var out = header(model, file: file)
    out += """
      //
      // Opens the bundle with the Swift runtime that came with the hand-over (kept in .shrinkml/runtime,
      // licence: \(kit.licenceName)). The three digests below are the bundle's own identity, read from
      // the hand-over when it was imported; the runtime checks the archive against the first before it
      // parses a byte, and the extracted files against the other two.
      // 用交付附的 Swift runtime 打開 bundle（runtime 放在 .shrinkml/runtime）。下面三個摘要是匯入時從交付讀到的 bundle 身分。
      @_exported import ShrinkMLPipelineRuntime
      import Foundation

      public enum \(model.name)Runtime {
        public static let bundleArchiveSHA256 = \(literal(kit.bundleArchiveSHA256))
        public static let bundleChecksum = \(literal(kit.bundleChecksum))
        public static let manifestSHA256 = \(literal(kit.manifestSHA256))

        public enum LoadError: Error { case bundleNotInModule }

        /// Extracts the bundle into `destination` (a folder that must not exist yet) and loads it.
        public static func load(extractingInto destination: URL) throws -> LoadedPipelineBundle {
          guard let url = \(model.name)Files.pipelineBundleURL else { throw LoadError.bundleNotInModule }
          return try PipelineBundleLoader.loadArchive(
            Data(contentsOf: url),
            expectedArchiveSha256: bundleArchiveSHA256,
            expectedBundleChecksum: bundleChecksum,
            expectedManifestSha256: manifestSHA256,
            extractingInto: destination)
        }
      }

      """
    return out
  }
